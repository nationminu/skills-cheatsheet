#!/usr/bin/env python3
"""테마 파일(shared/web/themes/*.md) → CSS 변수 블록 생성

사용:
  python3 scripts/theme-to-css.py shared/web/themes/slate.md            # Tailwind v4 (@theme + 다크 재정의)
  python3 scripts/theme-to-css.py shared/web/themes/slate.md --plain    # Tailwind 없이 쓰는 :root 변수
  python3 scripts/theme-to-css.py shared/web/themes/slate.md --shadcn   # shadcn/ui 변수 (shared/web/adapters/shadcn.md)

- 변수 이름은 Tailwind v4 규칙(--color-<토큰>)이라 bg-canvas, text-fg-muted 같은 유틸리티와 그대로 연결
- default-mode가 dark면 첫 화면을 다크로, system이면 OS 설정을 따름
"""
import re
import sys

REQUIRED = """canvas surface surface-muted line line-strong fg fg-muted fg-subtle
primary primary-hover primary-tint focus success success-tint warning warning-tint
danger danger-hover danger-tint chart-pending nav nav-raised nav-active nav-fg nav-muted nav-accent""".split()


def parse(path):
    text = open(path, encoding="utf-8").read()
    front = text.split("---\n", 2)[1]
    meta, colors, mode = {}, {}, None
    in_colors = False
    for line in front.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        key, _, val = line.strip().partition(":")
        val = val.strip().strip('"')
        if indent == 0:
            in_colors = key == "colors"
            if not in_colors:
                meta[key] = val
        elif in_colors and indent == 2:
            mode = key
            colors[mode] = {}
        elif in_colors and indent == 4 and mode:
            colors[mode][key] = val
    for m, c in colors.items():
        missing = [t for t in REQUIRED if t not in c]
        if missing:
            sys.exit(f"error: {path} [{m}] 필수 토큰 없음: {', '.join(missing)}")
        bad = [k for k, v in c.items() if not re.fullmatch(r"#[0-9A-Fa-f]{6}", v)]
        if bad:
            sys.exit(f"error: {path} [{m}] 색 값 형식 오류: {', '.join(bad)}")
    return meta, colors


def block(selector, c, pad="  "):
    lines = [f"{pad}--color-{k}: {v};" for k, v in c.items()]
    return f"{selector} {{\n" + "\n".join(lines) + "\n}"


# 우리 토큰 → shadcn/ui CSS 변수 (shared/web/adapters/shadcn.md 와 같은 표)
SHADCN = {
    "background": "canvas", "foreground": "fg",
    "card": "surface", "card-foreground": "fg",
    "popover": "surface", "popover-foreground": "fg",
    "primary": "primary", "primary-foreground": "surface",
    "secondary": "surface-muted", "secondary-foreground": "fg",
    "muted": "surface-muted", "muted-foreground": "fg-muted",
    "accent": "surface-muted", "accent-foreground": "fg",
    "destructive": "danger", "destructive-foreground": "surface",
    "border": "line", "input": "line-strong", "ring": "focus",
    "chart-5": "fg-muted",
    "sidebar": "nav", "sidebar-foreground": "nav-fg",
    "sidebar-primary": "nav-accent", "sidebar-primary-foreground": "nav",
    "sidebar-accent": "nav-active", "sidebar-accent-foreground": "nav-fg",
    "sidebar-border": "nav-raised", "sidebar-ring": "nav-accent",
}


def shadcn_vars(c, order):
    m = dict(SHADCN)
    for i, tok in enumerate(order[:4], 1):
        m[f"chart-{i}"] = tok
    out = {k: c[v] for k, v in m.items()}
    # 우리 토큰도 함께 정의 (bg-success-tint, text-fg-muted 등) — 이름이 겹치는 primary는 값이 같아 생략
    out.update({f"t-{k}": v for k, v in c.items() if k != "primary"})
    return out


def shadcn(meta, light, dark):
    order = [t.strip() for t in meta.get("chart-order", "primary, chart-pending, success, danger").strip("[]").split(",")]
    first = light or dark
    out = ['@import "tailwindcss";',
           '@custom-variant dark (&:is(.dark *, [data-theme="dark"] *));',
           ":root {\n  --radius: 0.625rem;\n" + "\n".join(f"  --{k}: {v};" for k, v in shadcn_vars(first, order).items()) + "\n}"]
    if light and dark:
        out.append('.dark, [data-theme="dark"] {\n' + "\n".join(f"  --{k}: {v};" for k, v in shadcn_vars(dark, order).items()) + "\n}")
    keys = list(shadcn_vars(first, order).keys())
    out.append("@theme inline {\n" + "\n".join(f"  --color-{k[2:] if k.startswith('t-') else k}: var(--{k});" for k in keys)
               + "\n  --radius-sm: calc(var(--radius) - 4px);\n  --radius-md: calc(var(--radius) - 2px);\n  --radius-lg: var(--radius);\n  --radius-xl: calc(var(--radius) + 4px);\n}")
    if meta.get("default-mode") == "dark" and dark:
        out.append('/* default-mode: dark → <html class="dark"> 로 시작 */')
    return out


def indent(text, pad="  "):
    return "\n".join(pad + l if l else l for l in text.splitlines())


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    path, plain = sys.argv[1], "--plain" in sys.argv
    meta, colors = parse(path)
    name = meta.get("name", "theme")
    default = meta.get("default-mode", "light")
    light, dark = colors.get("light"), colors.get("dark")
    base, alt, alt_name = (dark, light, "light") if default == "dark" and dark else (light or dark, dark, "dark")

    out = [f"/* theme: {name} — generated by scripts/theme-to-css.py, 직접 수정하지 말고 테마 파일을 고친 뒤 다시 생성 */"]
    if "--shadcn" in sys.argv:
        print("\n".join(out + shadcn(meta, light, dark)))
        return
    if plain:
        out.append(block(":root", base))
    else:
        out.append('@import "tailwindcss";')
        out.append(block("@theme", base))
    if alt:
        rules = [block(f'[data-theme="{alt_name}"]', alt)]
        if default == "system" and dark:
            rules.append("@media (prefers-color-scheme: dark) {\n" + indent(block(':root:not([data-theme="light"])', dark)) + "\n}")
        joined = "\n".join(rules)
        out.append(joined if plain else "@layer base {\n" + indent(joined) + "\n}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
